import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { rateLimit } from 'express-rate-limit';
import authRoutes from './modules/auth/auth.routes.js';
import productRoutes from './modules/products/products.routes.js';
import categoryRoutes from './modules/categories/categories.routes.js';
import salesRoutes from './modules/sales/sales.routes.js';
import reportRoutes from './modules/reports/reports.routes.js';
import { errorHandler } from './shared/errors.js';

export const app = express();
export default app;
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL?.split(',') ?? true }));
app.use(express.json({ limit: '1mb' }));
app.use(morgan('dev'));
app.use('/api/v1/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 100 }), authRoutes);
app.get('/health', (request, response) => response.json({ status: 'ok', service: 'pos-api' }));
app.use('/api/v1/products', productRoutes);
app.use('/api/v1/categories', categoryRoutes);
app.use('/api/v1/sales', salesRoutes);
app.use('/api/v1/reports', reportRoutes);
app.use((request, response) => response.status(404).json({ error: { message: 'Endpoint tidak ditemukan.' } }));
app.use(errorHandler);